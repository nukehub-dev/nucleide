    /// Analytic Bateman solution for A -> B -> C from pure A.
    fn bateman(n0: f64, t: f64) -> [f64; 3] {
        let na = n0 * (-L1 * t).exp();
        let nb = n0 * L1 / (L2 - L1) * ((-L1 * t).exp() - (-L2 * t).exp());
        let nc = n0 - na - nb;
        [na, nb, nc]
    }

    fn constant_steps(dt: f64, count: usize) -> Vec<Step> {
        (0..count)
            .map(|_| Step::new(dt, ReactionRates::new()))
            .collect()
    }

    fn max_rel_err(got: &[f64], want: &[f64]) -> f64 {
        got.iter()
            .zip(want)
            .map(|(g, w)| (g - w).abs() / w.max(1e-30))
            .fold(0.0_f64, f64::max)
    }

