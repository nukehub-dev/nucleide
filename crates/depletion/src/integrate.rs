    #[test]
    fn bateman_decay_series_all_integrators_match_oracle() {
        use crate::bateman::Method;
        // Cecm/Cf4 staging through the cached Bateman path: one build per
        // series, and bit-identical to the fresh per-step oracle on every
        // node (the oracle dispatches through the same analytic kernel).
        let sys = DepletionSystem::build(abc_chain(), &ReactionRates::new()).unwrap();
        let n0 = vec![1.0e15, 0.0, 0.0];
        let steps = constant_steps(2.0e4, 4);
        for method in [Method::Bateman, Method::BatemanHp] {
            for integrator in [Integrator::Cecm, Integrator::Cf4] {
                let mut stats = ReuseStats::default();
                let ts = integrate_with_method_counted(
                    &sys, &n0, &steps, integrator, method, &mut stats,
                )
                .unwrap();
                assert_eq!(
                    stats,
                    ReuseStats {
                        steps: 4,
                        system_builds: 1,
                        symbolic_builds: 1,
                        bateman_builds: 1,
                    },
                    "{method:?} {integrator:?}"
                );
                let mut n = n0.clone();
                for (k, step) in steps.iter().enumerate() {
                    n = advance(&sys, &n, step, integrator, method).unwrap();
                    assert_eq!(
                        ts.atoms[k + 1],
                        n,
                        "{method:?} {integrator:?} node {}",
                        k + 1
                    );
                }
                // Same analytic band as the Predictor arm.
                for (k, t) in ts.times.iter().enumerate() {
                    let want = bateman(n0[0], *t);
                    assert!(
                        max_rel_err(&ts.atoms[k], &want) < 1e-6,
                        "{method:?} {integrator:?} node {k}"
                    );
                }
            }
        }
    }

    #[test]
    fn bateman_fallback_series_all_integrators_match_oracle() {
        use crate::bateman::Method;
        // Live capture rate on A: every step falls back to CRAM-48 inside
        // the kernel (probe on step 1, cached fallback arm on steps 2+).
        // Cecm/Cf4 staging is bit-identical to the fresh per-step oracle and
        // stays within roundoff of the CRAM-method series.
        let a = ChainNuclide {
            name: "A".into(),
            half_life: Some(std::f64::consts::LN_2 / L1),
            decay_modes: vec![DecayMode {
                kind: "beta".into(),
                target: "B".into(),
                branching_ratio: 1.0,
            }],
            reactions: vec![crate::chain::Reaction {
                kind: "(n,gamma)".into(),
                target: Some("B".into()),
                q: 0.0,
                branching_ratio: 1.0,
            }],
            ..Default::default()
        };
        let b = ChainNuclide {
            name: "B".into(),
            half_life: Some(std::f64::consts::LN_2 / L2),
            decay_modes: vec![DecayMode {
                kind: "beta".into(),
                target: "C".into(),
                branching_ratio: 1.0,
            }],
            ..Default::default()
        };
        let c = ChainNuclide {
            name: "C".into(),
            ..Default::default()
        };
        let chain = Chain::from_nuclides(vec![a, b, c]).unwrap();
        let sys = DepletionSystem::build(chain, &ReactionRates::new()).unwrap();
        let mut rates = ReactionRates::new();
        rates
            .entry(0usize)
            .or_default()
            .insert("(n,gamma)".to_string(), 1e-7);
        let steps: Vec<Step> = (0..3).map(|_| Step::new(2.0e4, rates.clone())).collect();
        let n0 = vec![1.0e15, 0.0, 0.0];
        for integrator in [Integrator::Cecm, Integrator::Cf4] {
            let cref = integrate_with_method(&sys, &n0, &steps, integrator, Method::default_cram())
                .unwrap();
            for method in [Method::Bateman, Method::BatemanHp] {
                let got = integrate_with_method(&sys, &n0, &steps, integrator, method).unwrap();
                let mut n = n0.clone();
                for (k, step) in steps.iter().enumerate() {
                    n = advance(&sys, &n, step, integrator, method).unwrap();
                    assert_eq!(
                        got.atoms[k + 1],
                        n,
                        "{method:?} {integrator:?} node {}",
                        k + 1
                    );
                }
                for (k, row) in got.atoms.iter().enumerate() {
                    let err = max_rel_err(row, &cref.atoms[k]);
                    assert!(err < 1e-9, "{method:?} {integrator:?} node {k}: {err}");
                }
            }
        }
    }
