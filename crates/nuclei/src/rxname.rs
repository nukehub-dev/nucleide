//! The registry holds all 574 reactions including alternate-projectile
//! channels resolved through [`Projectile`] flags (`'n'`, `'p'`, `'d'`,
//! `'t'`, `'He3'`, `'a'`, `'gamma'`, `'decay'`).
//!
//! Reaction ids are `hash(name)` with a seed of 32, so every id is ≥ 1000
//! and never collides with an ENDF MT number.

