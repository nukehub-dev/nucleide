/// Resolve a reaction spec — canonical name, alternate name, numeric id, or
/// numeric MT number — to its canonical reaction id.
///
/// ```
/// use nuclei::rxname;
/// assert_eq!(rxname::name_to_id("fission"), Ok(rxname::hash("fission")));
/// assert_eq!(rxname::name_to_id("alpha"), Ok(rxname::hash("a")));
/// assert_eq!(rxname::name_to_id("107"), Ok(rxname::hash("a"))); // MT 107
/// ```
pub fn name_to_id(spec: &str) -> Result<u32, Error> {
    if let Some(id) = canonical_id(spec).or_else(|| alt_id(spec)) {
        return Ok(id);
    }
    // Numeric strings resolve as reaction ids first, then MT numbers.
    if !spec.is_empty() && spec.bytes().all(|b| b.is_ascii_digit()) {
        if let Ok(n) = spec.parse::<u32>() {
            if id_to_name(n).is_some() {
                return Ok(n);
            }
        }
        if let Ok(n) = spec.parse::<i32>() {
            return mt_to_id(n);
        }
    }
    Err(Error::NotAReaction(spec.to_string()))
}

/// Canonical name for a reaction id.
#[must_use]
pub fn id_to_name(id: u32) -> Option<&'static str> {
    reaction(id).map(|r| r.name)
}

/// Reaction id carrying ENDF MT number `mt`.
///
/// Only positive MT numbers are registered (none for MT 0).
pub fn mt_to_id(mt: i32) -> Result<u32, Error> {
    REACTIONS
        .iter()
        .find(|r| r.mt > 0 && r.mt == mt)
        .map(|r| r.id)
        .ok_or(Error::UnknownMt(mt))
}

/// ENDF MT number for a reaction id; `0` when the reaction has none or the
/// id is unknown (the sentinel keeps the signature total).
#[must_use]
pub fn id_to_mt(id: u32) -> i32 {
    reaction(id).map_or(0, |r| r.mt)
}

/// `"(z,a)"`-style short label; empty for unknown ids (the C++ map default).
#[must_use]
pub fn label(id: u32) -> &'static str {
    reaction(id).map_or("", |r| r.label)
}

/// Long documentation string; empty for unknown ids.
#[must_use]
pub fn doc(id: u32) -> &'static str {
    reaction(id).map_or("", |r| r.doc)
}

/// Registry row for a reaction id.
#[must_use]
pub fn reaction(id: u32) -> Option<&'static Reaction> {
    REACTIONS
        .binary_search_by_key(&id, |r| r.id)
        .ok()
        .map(|i| &REACTIONS[i])
}

/// `(ΔZ, ΔA, Δstate)` between parent ground state and daughter.
pub type NucDelta = (i32, i32, i32);

/// Decode a packed channel offset `dz*10^7 + da*10^4 + ds`.
const fn unpack_offset(diff: i64) -> NucDelta {
    let r = diff.rem_euclid(10_000);
    let ds = if r < 5_000 { r } else { r - 10_000 };
    let combined = (diff - ds).div_euclid(10_000);
    let da_raw = combined.rem_euclid(1_000);
    let da = if da_raw < 500 { da_raw } else { da_raw - 1_000 };
    let dz = (combined - da).div_euclid(1_000);
    (dz as i32, da as i32, ds as i32)
}

