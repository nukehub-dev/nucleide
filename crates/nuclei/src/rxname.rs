/// Errors from reaction-name resolution.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Error {
    /// Input did not resolve to any reaction (name, alias, id, or MT).
    NotAReaction(String),
    /// No registered reaction carries this MT number.
    UnknownMt(i32),
    /// No registered channel for this projectile and nuclide difference.
    Indeterminate {
        projectile: Projectile,
        delta: NucDelta,
    },
    /// No registered nuclide offset for this projectile and reaction.
    UnknownOffset { projectile: Projectile, id: u32 },
    /// Daughter/parent nuclide resulting from the channel is not physical.
    BadNuclide(crate::Error),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Error::NotAReaction(s) => write!(f, "not a reaction: `{s}`"),
            Error::UnknownMt(mt) => write!(f, "no reaction carries MT number {mt}"),
            Error::Indeterminate { projectile, delta } => {
                write!(f, "indeterminate reaction form: {projectile:?} {delta:?}")
            }
            Error::UnknownOffset { projectile, id } => {
                write!(
                    f,
                    "no offset registered for {projectile:?} reaction id {id}"
                )
            }
            Error::BadNuclide(e) => write!(f, "channel yields invalid nuclide: {e}"),
        }
    }
}

impl std::error::Error for Error {}

/// Incident-particle flag disambiguating reaction channels. Variant order defines table sort order.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Default)]
pub enum Projectile {
    /// Neutron-induced (`"n"`); the default.
    #[default]
    Neutron,
    /// Proton-induced (`"p"`).
    Proton,
    /// Deuteron-induced (`"d"`).
    Deuteron,
    /// Triton-induced (`"t"`).
    Triton,
    /// Helion-3-induced (`"He3"`).
    Helion3,
    /// Alpha-induced (`"a"`).
    Alpha,
    /// Gamma-induced (`"gamma"`), e.g. photonnuclear channels.
    Gamma,
    /// Radioactive-decay channel (`"decay"`).
    Decay,
}

impl Projectile {
    /// Parse a projectile flag string.
    pub fn from_flag(flag: &str) -> Result<Self, Error> {
        match flag.trim() {
            "n" => Ok(Self::Neutron),
            "p" => Ok(Self::Proton),
            "d" => Ok(Self::Deuteron),
            "t" => Ok(Self::Triton),
            "He3" => Ok(Self::Helion3),
            "a" => Ok(Self::Alpha),
            "gamma" => Ok(Self::Gamma),
            "decay" => Ok(Self::Decay),
            s => Err(Error::NotAReaction(s.to_string())),
        }
    }

    /// The canonical flag string for this projectile.
    #[must_use]
    pub const fn flag(self) -> &'static str {
        match self {
            Self::Neutron => "n",
            Self::Proton => "p",
            Self::Deuteron => "d",
            Self::Triton => "t",
            Self::Helion3 => "He3",
            Self::Alpha => "a",
            Self::Gamma => "gamma",
            Self::Decay => "decay",
        }
    }
}

impl std::str::FromStr for Projectile {
    type Err = Error;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        Self::from_flag(s)
    }
}

/// Reaction hash: `h = ((h << 5) + h) ^ c` seeded at 32 (wrapping).
/// The seed keeps every result ≥ 1000, reserving that range for MT numbers.
#[must_use]
pub const fn hash(name: &str) -> u32 {
    let bytes = name.as_bytes();
    let mut h: u32 = 32;
    let mut i = 0;
    while i < bytes.len() {
        h = (h << 5).wrapping_add(h) ^ (bytes[i] as u32);
        i += 1;
    }
    h
}

