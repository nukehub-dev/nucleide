"""Render validation/results.md from the machine-readable JSON reports."""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

SCRIPT_DIR = Path(__file__).resolve().parent
RESULTS_DIR = SCRIPT_DIR / "results"
RESULTS_MD = SCRIPT_DIR / "results.md"
ENVIRONMENT_JSON = SCRIPT_DIR / "environment.json"

SECTION_ORDER = ["depletion", "enrichment", "magic", "nuclear_data", "timings"]


def _pyne_metadata_version() -> str:
    """Return ``pyne.__version__`` for the stale-metadata caveat."""
    try:
        import pyne

        return str(pyne.__version__)
    except Exception:
        return "0.7.1"


def load_reports() -> dict[str, dict[str, Any]]:
    """Load all result JSON files keyed by report name."""
    reports: dict[str, dict[str, Any]] = {}
    if not RESULTS_DIR.exists():
        print(
            f"ERROR: {RESULTS_DIR} does not exist; run the validation scripts first.",
            file=sys.stderr,
        )
        raise SystemExit(1)
    for path in sorted(RESULTS_DIR.glob("*.json")):
        data = json.loads(path.read_text())
        reports[data["name"]] = data
    return reports


def load_environment_annotations() -> dict[str, str]:
    """Load hand-maintained source annotations for the environment table."""
    data = json.loads(ENVIRONMENT_JSON.read_text())
    return {str(k): str(v) for k, v in data.items()}


def render_table(headers: list[str], rows: list[list[str]]) -> list[str]:
    """Render a pipe-aligned Markdown table."""
    widths = [max(len(str(row[i])) for row in [headers] + rows) for i in range(len(headers))]
    lines: list[str] = []
    lines.append(
        "| " + " | ".join(str(headers[i]).ljust(widths[i]) for i in range(len(headers))) + " |"
    )
    lines.append("|" + "|".join("-" * (widths[i] + 2) for i in range(len(headers))) + "|")
    for row in rows:
        lines.append(
            "| " + " | ".join(str(row[i]).ljust(widths[i]) for i in range(len(headers))) + " |"
        )
    return lines


def render_section(section: dict[str, Any]) -> list[str]:
    """Render one report section to Markdown lines."""
    lines: list[str] = []
    kind = section["kind"]
    if kind == "heading":
        prefix = "#" * section["level"]
        lines.append(f"{prefix} {section['text']}")
    elif kind == "prose":
        lines.append(section["text"])
    elif kind == "table":
        lines.extend(render_table(section["headers"], section["rows"]))
    return lines


def render_environment_table(env: dict[str, str], annotations: dict[str, str]) -> list[str]:
    """Render the Code/Version/Source environment table."""
    # Python version is reported as major.minor to match the paper table.
    python_version = env["python"]
    parts = python_version.split(".")
    if len(parts) >= 2:
        python_version = f"{parts[0]}.{parts[1]}"
    rows = [
        ["Nucleide", env["nucleide"], annotations.get("Nucleide", "")],
        ["PyNE", env["pyne"], annotations.get("PyNE", "")],
        ["OpenMC", env["openmc"], annotations.get("OpenMC", "")],
        ["Python", python_version, annotations.get("Python", "")],
    ]
    return render_table(["Code", "Version", "Source"], rows)


def render(reports: dict[str, dict[str, Any]], annotations: dict[str, str]) -> str:
    """Render the full results.md document."""
    first_env = next(iter(reports.values()))["environment"]
    date = first_env["date"]
    pyne_metadata = _pyne_metadata_version()
    pyne_version = first_env["pyne"]

    lines: list[str] = [
        "# Nucleide cross-code validation results",
        "",
        "These numbers were generated by the runnable scripts in this directory on",
        f"**{date}**, inside the container built from `Containerfile`",
        "(`./validation/run_container.sh`, podman). The environment versions were:",
        "",
    ]
    lines.extend(render_environment_table(first_env, annotations))
    lines.extend(
        [
            "",
            "(`pyne.__version__` reads "
            f"{pyne_metadata} — stale upstream metadata; the conda package",
            "version is the truth.)",
            "",
            f"PyNE {pyne_version} is numerically identical to 0.7.8 for every module "
            "exercised here",
            "(the 0.7.5..0.7.8 diff in `enrichment.cpp`/`data.cpp`/`atomic_mass.py` is",
            "cosmetic; 0.7.8 cannot build on Python 3.12). An earlier run against the",
            "conda-forge PyNE 0.7.1 + OpenMC 0.15.3 environment produced **identical**",
            "correctness numbers; only wall-time figures moved.",
            "",
            "All values below are taken directly from `./validation/run_all.sh` output and",
            "are not hand-edited. See `README.md` for how to regenerate them.",
            "",
        ]
    )

    for idx, name in enumerate(SECTION_ORDER, start=1):
        if name not in reports:
            print(f"WARNING: missing report '{name}'; skipping.", file=sys.stderr)
            continue
        report = reports[name]
        lines.append(f"## {idx}. {report['title']}")
        lines.append("")
        for section in report["sections"]:
            lines.extend(render_section(section))
            lines.append("")

    # Remove a single trailing blank line before the file-ending newline.
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def main() -> int:
    reports = load_reports()
    annotations = load_environment_annotations()
    missing = [name for name in SECTION_ORDER if name not in reports]
    if missing:
        print(f"ERROR: missing reports: {missing}", file=sys.stderr)
        return 1
    RESULTS_MD.write_text(render(reports, annotations))
    print(f"Wrote {RESULTS_MD}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
